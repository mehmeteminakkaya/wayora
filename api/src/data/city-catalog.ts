export function catalogGooglePlaceId(citySlug: string, experienceSlug: string): string {
  return `catalog:${citySlug}:${experienceSlug}`
}

export function findCatalogCity(input: string): CatalogCity | undefined {
  const needle = normalizeCity(input)
  return CITY_CATALOG.find(
    (city) => city.slug === needle || city.aliases.some((alias) => normalizeCity(alias) === needle),
  )
}

export function normalizeCity(input: string): string {
  return input
    .trim()
    .toLocaleLowerCase('tr-TR')
    .replaceAll('ı', 'i')
    .replaceAll('İ', 'i')
    .replaceAll('ş', 's')
    .replaceAll('ğ', 'g')
    .replaceAll('ü', 'u')
    .replaceAll('ö', 'o')
    .replaceAll('ç', 'c')
    .replaceAll('â', 'a')
    .replaceAll('î', 'i')
}
